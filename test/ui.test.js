import { test } from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { harness } from './helpers.js';

test('browser: registration, verification, batch awards and sequential synchronized reveals on mobile', async () => {
  const h = await harness();
  const server = h.app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  let browser;
  try {
    browser = await chromium.launch({ headless: true });
    const base = `http://127.0.0.1:${server.address().port}`;
    const errors = [];
    const context = await browser.newContext();
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base);
    await page.getByRole('heading', { name: 'CSI Solution 2026 Lucky Draw', exact: true }).waitFor();
    await page.getByRole('link', { name: 'Join the celebration' }).click();
    await page.getByLabel('Your name').fill('Browser Employee');
    await page.getByLabel('Email address', { exact: true }).fill('browser@gmail.com');
    await page.getByRole('button', { name: 'Register for the event' }).click();
    await page.getByRole('heading', { name: 'Hello, Browser Employee.' }).waitFor();
    assert.ok(await page.getByText('Your registration is awaiting admin approval.', { exact: false }).isVisible());
    const adminContext = await browser.newContext();
    const admin = await adminContext.newPage();
    admin.on('pageerror', error => errors.push(error.message));
    await admin.goto(`${base}/#admin`);
    await admin.getByLabel('Admin email').fill(h.config.adminEmail);
    await admin.getByLabel('Admin password').fill(h.config.adminPassword);
    await admin.getByRole('button', { name: 'Sign in to admin' }).click();
    await admin.getByRole('button', { name: 'Manage', exact: true }).click();
    await admin.getByLabel('Approved for this event').check();
    await admin.getByText('Employee approval updated.', { exact: true }).waitFor();
    await admin.getByLabel('Appreciate a colleague', { exact: false }).check();
    await admin.getByText('Activity verification and ticket allocation updated.', { exact: true }).waitFor();
    await page.reload();
    await page.getByText(/CSI-\d+ \/ BONUS/).waitFor();
    await h.add('Offline Employee', 'offline@example.com');
    await admin.getByRole('button', { name: 'Settings', exact: true }).click();
    await admin.getByLabel('Event status').selectOption('live');
    await admin.getByRole('button', { name: 'Save event settings' }).click();
    await admin.getByText('Saved successfully.', { exact: true }).waitFor();
    await admin.getByRole('button', { name: 'Run the draw', exact: true }).click();
    const publicContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const audience = await publicContext.newPage();
    audience.on('pageerror', error => errors.push(error.message));
    await audience.goto(`${base}/?event=1#draw`);
    await audience.getByRole('heading', { name: 'Your moment is coming.', exact: true }).waitFor();
    assert.equal(await audience.getByRole('button', { name: 'Roll & reveal' }).count(), 0);
    await audience.evaluate(() => {
      Object.defineProperty(document, 'hidden', { configurable: true, get: () => true });
    });
    await admin.getByLabel('Prize name for this selection').fill('A festive hamper');
    await admin.getByLabel('Number of winners', { exact: true }).fill('5');
    const started = Date.now();
    const selectionResponse = admin.waitForResponse(response => response.url().endsWith('/draw') && response.request().method() === 'POST');
    await admin.getByRole('button', { name: 'Roll & reveal' }).click();
    const selection = await (await selectionResponse).json();
    assert.equal(selection.winner_count, 2);
    assert.equal(selection.reduced, true);
    const names = (await h.pool.query('SELECT id,name FROM people WHERE event_id=1')).rows;
    const firstName = names.find(p => p.id === selection.draws[0].person_id).name;
    const secondName = names.find(p => p.id === selection.draws[1].person_id).name;
    await admin.getByRole('heading', { name: 'Let the luck roll!', exact: true }).waitFor();
    await audience.getByRole('heading', { name: 'Let the luck roll!', exact: true }).waitFor();
    await audience.evaluate(() => {
      delete document.hidden;
      document.dispatchEvent(new Event('visibilitychange'));
      window.dispatchEvent(new Event('focus'));
    });
    assert.equal(await admin.getByRole('heading', { name: 'Browser Employee', exact: true }).count(), 0);
    assert.equal(await admin.getByRole('button', { name: 'Present & claimed', exact: true }).count(), 0);
    assert.equal(await admin.getByRole('button', { name: 'Absent', exact: false }).count(), 0);
    assert.equal(await admin.getByRole('button', { name: 'Roll & reveal' }).isDisabled(), true);
    await admin.getByText('Winner 1 of 2', { exact: false }).waitFor();
    await admin.getByText('5 requested; 2 available', { exact: false }).first().waitFor();
    await admin.waitForFunction(() => document.querySelectorAll('.reel-digit.settled').length >= 1);
    const settled = await admin.locator('.reel-digit.settled').count();
    assert.ok(settled >= 1 && settled < 6);
    assert.equal(await audience.getByRole('heading', { name: 'Browser Employee', exact: true }).count(), 0);
    assert.equal(await audience.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    const lateViewer = await publicContext.newPage();
    await lateViewer.emulateMedia({ reducedMotion: 'reduce' });
    await lateViewer.goto(`${base}/?event=1#draw`);
    await lateViewer.getByRole('heading', { name: 'Let the luck roll!', exact: true }).waitFor();
    await lateViewer.waitForFunction(() => document.querySelectorAll('.reel-digit.settled').length >= 1);
    assert.equal(await lateViewer.locator('.reel-digit.rolling').first().textContent(), '?');
    await admin.getByRole('heading', { name: firstName, exact: true }).waitFor();
    assert.ok(Date.now() - started >= 9900);
    await audience.getByRole('heading', { name: firstName, exact: true }).waitFor();
    await lateViewer.getByRole('heading', { name: firstName, exact: true }).waitFor();
    const selectedCode = `CSI-${String(selection.draws[0].ticket_id).padStart(6, '0')}`;
    assert.equal(await admin.locator('#draw-stage .ticket-code').textContent(), selectedCode);
    assert.equal(await audience.locator('#draw-stage .ticket-code').textContent(), selectedCode);
    assert.equal(await audience.locator('#winners-list .winner-item').count(), 1);
    assert.equal(await audience.getByRole('heading', { name: secondName, exact: true }).count(), 0);
    await admin.getByText('Winner 2 of 2', { exact: false }).waitFor();
    await admin.getByRole('heading', { name: 'Let the luck roll!', exact: true }).waitFor();
    await audience.getByText('Winner 2 of 2', { exact: false }).waitFor();
    await audience.getByRole('heading', { name: 'Let the luck roll!', exact: true }).waitFor();
    await lateViewer.reload();
    await lateViewer.getByText('Winner 2 of 2', { exact: false }).waitFor();
    await lateViewer.getByRole('heading', { name: 'Let the luck roll!', exact: true }).waitFor();
    await admin.getByRole('heading', { name: secondName, exact: true }).waitFor();
    assert.ok(Date.now() - started >= 21900);
    await audience.getByRole('heading', { name: secondName, exact: true }).waitFor();
    const secondCode = `CSI-${String(selection.draws[1].ticket_id).padStart(6, '0')}`;
    assert.equal(await audience.locator('#draw-stage .ticket-code').textContent(), secondCode);
    assert.equal(await audience.locator('#winners-list .winner-item').count(), 2);
    assert.equal(await admin.getByRole('button', { name: 'Roll & reveal' }).isDisabled(), true);
    await page.reload();
    await page.getByRole('region', { name: 'Your golden winning ticket' }).waitFor();
    await page.locator('.golden-ticket').getByText('You won A festive hamper.', { exact: true }).waitFor();
    const employeeDraw = selection.draws.find(draw => draw.person_id === names.find(p => p.name === 'Browser Employee').id);
    assert.equal(await page.locator('.golden-ticket-stub strong').textContent(), `CSI-${String(employeeDraw.ticket_id).padStart(6, '0')}`);
    assert.ok((await page.locator('.golden-ticket blockquote').textContent()).includes('CSI'));
    const message = await page.locator('.golden-ticket blockquote').textContent();
    await page.getByRole('link', { name: 'Home', exact: true }).click();
    await page.getByRole('link', { name: 'My tickets', exact: true }).click();
    assert.equal(await page.locator('.golden-ticket blockquote').textContent(), message);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await audience.goto(`${base}/?event=1#draw`);
    await audience.getByText('Prize awarded', { exact: false }).first().waitFor();
    assert.equal(await audience.getByText('browser@gmail.com', { exact: true }).count(), 0);
    assert.ok(await audience.getByText('A festive hamper', { exact: true }).first().isVisible());
    assert.equal(await audience.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await audience.goto(`${base}/#home`);
    await audience.getByRole('heading', { name: 'CSI Solution 2026 Lucky Draw', exact: true }).waitFor();
    assert.equal(await audience.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    assert.deepEqual(errors, []);
    await adminContext.close();
    await publicContext.close();
    await context.close();
  } finally {
    await browser?.close();
    await new Promise(resolve => server.close(resolve));
    await h.pool.end();
  }
});

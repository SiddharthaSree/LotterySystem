import { test } from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { harness } from './helpers.js';

test('browser: signup, admin approval, verification, live selection, claim, public screen and mobile layout', async () => {
  const h = await harness();
  const server = h.app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  let browser;
  try {
    browser = await chromium.launch({ headless: true });
    const base = `http://127.0.0.1:${server.address().port}`;
    const errors = [];
    const context = await browser.newContext();
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base);
    await page.getByRole('heading', { name: 'CSI Solution 2026 Lucky Draw', exact: true }).waitFor();
    await page.getByRole('link', { name: 'Join the celebration' }).click();
    await page.getByLabel('Your name').fill('Browser Employee');
    await page.getByLabel('Email address', { exact: true }).fill('browser@gmail.com');
    await page.getByRole('button', { name: 'Register for the event' }).click();
    await page.getByRole('heading', { name: 'Hello, Browser Employee.' }).waitFor();
    assert.ok(await page.getByText('Your registration is awaiting admin approval.', { exact: false }).isVisible());
    const adminContext = await browser.newContext();
    const admin = await adminContext.newPage();
    admin.on('pageerror', error => errors.push(error.message));
    await admin.goto(`${base}/#admin`);
    await admin.getByLabel('Admin email').fill(h.config.adminEmail);
    await admin.getByLabel('Admin password').fill(h.config.adminPassword);
    await admin.getByRole('button', { name: 'Sign in to admin' }).click();
    await admin.getByRole('button', { name: 'Manage', exact: true }).click();
    await admin.getByLabel('Approved for this event').check();
    await admin.getByText('Employee approval updated.', { exact: true }).waitFor();
    await admin.getByLabel('Appreciate a colleague', { exact: false }).check();
    await admin.getByText('Activity verification and ticket allocation updated.', { exact: true }).waitFor();
    await page.reload();
    await page.getByText(/CSI-\d+ \/ BONUS/).waitFor();
    await admin.getByRole('button', { name: 'Settings', exact: true }).click();
    await admin.getByLabel('Event status').selectOption('live');
    await admin.getByRole('button', { name: 'Save event settings' }).click();
    await admin.getByText('Saved successfully.', { exact: true }).waitFor();
    await admin.getByRole('button', { name: 'Run the draw', exact: true }).click();
    await admin.getByLabel('Prize name for this selection').fill('A festive hamper');
    await admin.getByRole('button', { name: 'Select a lucky ticket' }).click();
    await admin.getByRole('heading', { name: 'Browser Employee', exact: true }).waitFor();
    admin.once('dialog', dialog => dialog.accept());
    await admin.getByRole('button', { name: 'Present & claimed', exact: true }).click();
    await admin.getByText('Prize claimed. All tickets for this winner are now excluded.', { exact: true }).waitFor();
    const publicContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const audience = await publicContext.newPage();
    await audience.goto(`${base}/?event=1#draw`);
    await audience.getByText('Prize claimed', { exact: false }).first().waitFor();
    assert.equal(await audience.getByText('browser@gmail.com', { exact: true }).count(), 0);
    assert.ok(await audience.getByText('A festive hamper', { exact: true }).first().isVisible());
    assert.equal(await audience.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await audience.goto(`${base}/#home`);
    await audience.getByRole('heading', { name: 'CSI Solution 2026 Lucky Draw', exact: true }).waitFor();
    assert.equal(await audience.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    assert.deepEqual(errors, []);
    await adminContext.close();
    await publicContext.close();
    await context.close();
  } finally {
    await browser?.close();
    await new Promise(resolve => server.close(resolve));
    await h.pool.end();
  }
});
